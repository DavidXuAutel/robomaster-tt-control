#!/usr/bin/env bash
# One-key Phase-1 deploy + verify, run ON the 4090 (10.229.20.125), localhost renderer.
#
# 边界（诚实）：本脚本假设系统前置已手动装好，且 bridge 由你在另一个终端常驻。
#   不装：NVIDIA 驱动 / CUDA / ROS2 Humble / conda 本体   (SETUP.md §1.1)
#   不下：AirSim 场景（HF 文件名多变）                      (SETUP.md §1.6)
#   不启：env_bridge.py（单消费者，必须独立终端常驻）      (SETUP.md §1.8)
# 缺以上任一项时，脚本会停在对应 gate 并打印准确的下一步，不会假装成功。
#
# 它幂等地做的事：
#   1. （可选）拉 aerial-sim-verify 分支到最新
#   2. 写 Phase-1 localhost 的 config.env（已存在则不覆盖）
#   3. preflight → setup_env(CONFIRM 自动补 OpenFly 层) → preflight 复检
#   4. 检查 bridge 端口 127.0.0.1:41451 活着，否则停并提示
#   5. run_all.sh → 打印 Fork A / A⁻ / B（退出码 0 / 2 / 3）
#
# 用法（在 4090 上，sim_verify 目录内）：
#   OPENFLY_ROOT=/data/OpenFly-Platform ./deploy_4090.sh
# 可选：
#   ENV_NAME=env_airsim_16   AIRSIM_PORT=41451
#   PULL=1     # 先 git pull 本分支（默认 0，不动你的工作区）
#   SKIP_SETUP=1  # 跳过 setup_env（环境已就绪、只想重验时）
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"; cd "$HERE"

OPENFLY_ROOT="${OPENFLY_ROOT:-}"
ENV_NAME="${ENV_NAME:-env_airsim_16}"
AIRSIM_HOST="${AIRSIM_HOST:-127.0.0.1}"   # Phase 1 单机 localhost
AIRSIM_PORT="${AIRSIM_PORT:-41451}"
PULL="${PULL:-0}"
SKIP_SETUP="${SKIP_SETUP:-0}"

die(){ echo; echo "[deploy] ✗ $*" >&2; exit 1; }
say(){ echo "[deploy] $*"; }

[ -n "$OPENFLY_ROOT" ] || die "先设 OPENFLY_ROOT，例如：OPENFLY_ROOT=/data/OpenFly-Platform ./deploy_4090.sh"

# --- 0) 可选拉最新分支（默认不动工作区，避免踩你未提交的改动）---
if [ "$PULL" = "1" ]; then
  if git -C "$HERE" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    say "git pull aerial-sim-verify …"
    git -C "$HERE" pull --ff-only 2>&1 | tail -3 || say "pull 未 ff（有本地改动？）—— 跳过，用现有代码继续"
  else
    say "非 git 工作区，跳过 pull"
  fi
fi

# --- 1) Phase-1 localhost config.env（已存在则尊重现有，不覆盖）---
if [ -f ./config.env ]; then
  say "沿用已存在的 config.env（如需重置，先删掉它）"
else
  say "生成 Phase-1 localhost config.env"
  cat > ./config.env <<EOF
# Auto-generated by deploy_4090.sh (Phase 1, localhost renderer). Edit freely.
export AIRSIM_HOST=$AIRSIM_HOST
export AIRSIM_PORT=$AIRSIM_PORT
export AIRSIM_CAMERA=0
export OPENFLY_ROOT=$OPENFLY_ROOT
export ENV_NAME=$ENV_NAME
export L2F_N=10
export L2F_INTERVAL_S=0.05
export L2F_MIN_FPS=5.0
export OUT=./artifacts/sim_capability_report.json
EOF
fi

# --- 2) 环境检查 → 缺则补 → 复检 ---
say "preflight（只读检查）…"
./preflight.sh || say "preflight 有未通过项（下面 setup_env 会尝试补）"

if [ "$SKIP_SETUP" = "1" ]; then
  say "SKIP_SETUP=1 —— 跳过 setup_env"
else
  say "setup_env（CONFIRM=1 自动补 OpenFly 层缺失项）…"
  CONFIRM=1 ./setup_env.sh || die "setup_env 失败：缺系统前置(§1.1) 或场景(§1.6) 需手动处理，见上方输出"
  say "preflight 复检 …"
  ./preflight.sh || say "复检仍有未通过项 —— 若为系统前置/场景，需手动处理后重跑"
fi

# --- 3) bridge 端口门禁（不自启，单消费者常驻）---
say "检查 bridge 端口 $AIRSIM_HOST:$AIRSIM_PORT …"
if (exec 3<>"/dev/tcp/$AIRSIM_HOST/$AIRSIM_PORT") 2>/dev/null; then
  exec 3>&- 3<&-
  say "✓ 端口活着"
else
  die "$AIRSIM_HOST:$AIRSIM_PORT 连不上。请在另一个终端先启动 bridge（常驻，等到 'ready to be connected'）：
       cd $OPENFLY_ROOT && conda activate openfly
       source /opt/ros/humble/setup.bash
       python scripts/sim/env_bridge.py --env $ENV_NAME
     （SETUP.md §1.8）"
fi

# --- 4) 跑验证并透传 Fork 退出码 ---
say "run_all.sh → Fork 判定 …"
echo
./run_all.sh
code=$?
echo
case "$code" in
  0) say "结论：Fork A（IMU/深度/碰撞/物理全可用）→ v2 pure-vision 可行，可进 Phase 2 RL" ;;
  2) say "结论：Fork A⁻（相机+深度有，IMU/物理无）→ 疑 ComputerVision 模式，见 SETUP.md §1.7 切 Multirotor 重验" ;;
  3) say "结论：Fork B（无真渲染/连不上）→ v2 不可达，回退方案" ;;
  *) say "run_all 退出码 $code（异常，非判定码）—— 看上方输出与 artifacts/sim_capability_report.json" ;;
esac
exit $code
